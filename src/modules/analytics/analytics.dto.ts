export class AnalyticsEventDto {
  @ApiProperty({
    format: 'uuid',
    example: IDS.event,
    description: 'Generated by the client; a replay is ignored',
  })
  @IsUUID()
  eventId!: string;

  @ApiProperty({ enum: ANALYTICS_EVENT_NAMES, enumName: 'AnalyticsEventName', example: 'quote_shown' })
  @IsIn(ANALYTICS_EVENT_NAMES)
  name!: (typeof ANALYTICS_EVENT_NAMES)[number];

  @ApiProperty({
    format: 'date-time',
    example: '2026-10-01T10:15:00+07:00',
    description: 'Up to 7 days old; later ones are dropped',
  })
  @IsISO8601({ strict: true })
  occurredAt!: string;

  @ApiProperty({
    example: 'a8Kd02mZqL5x',
    pattern: CLIENT_ID.source,
    description: 'First-party visitor id (cookie); kept only with analytics consent',
  })
  @Matches(CLIENT_ID)
  anonymousId!: string;

  @ApiProperty({
    example: 's-7f3c91d2e0',
    pattern: CLIENT_ID.source,
    description: 'Session id; kept only with analytics consent',
  })
  @Matches(CLIENT_ID)
  sessionId!: string;

  @ApiPropertyOptional({
    example: '/configure/folding_carton',
    maxLength: 500,
    description: 'Query string and identifier-like segments are removed',
  })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  pagePath?: string;

  @ApiPropertyOptional({ example: 'folding_carton', pattern: '^[a-z0-9_]{1,60}$' })
  @IsOptional()
  @Matches(/^[a-z0-9_]{1,60}$/)
  productTypeCode?: string;

  @ApiPropertyOptional({
    type: 'object',
    additionalProperties: true,
    example: { quantity: 1000, instant: true, leadTimeDays: 12, unitPrice: '4.250000' },
    description:
      'Closed schema per event — page_view {pageType, referrerHost}; configurator_step {step, stepIndex}; quote_shown {quantity, instant, leadTimeDays, unitPrice}; add_to_cart {quantity}; checkout_step {step, orderGroupId (placed only)}. Quantities are stored as bands.',
  })
  @IsOptional()
  @IsObject()
  properties?: Record<string, unknown>;

  @ApiPropertyOptional({ type: UtmDto })
  @IsOptional()
  @ValidateNested()
  @Type(() => UtmDto)
  utm?: UtmDto;

  @ApiPropertyOptional({ enum: DEVICE_CLASSES, enumName: 'DeviceClass', example: 'mobile' })
  @IsOptional()
  @IsIn(DEVICE_CLASSES)
  deviceClass?: (typeof DEVICE_CLASSES)[number];

  @ApiPropertyOptional({
    example: '10110',
    pattern: '^\\d{5}$',
    description: 'Delivery postcode; stored only as its province, with consent',
  })
  @IsOptional()
  @Matches(/^\d{5}$/)
  postcode?: string;
}

