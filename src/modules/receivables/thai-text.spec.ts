import { bahtText, thaiDate, thaiMonth, thaiNumber } from './thai-text';

describe('Thai document wording (B5.2)', () => {
  it.each([
    ['0.00', 'ศูนย์บาทถ้วน'],
    ['1.00', 'หนึ่งบาทถ้วน'],
    ['11.00', 'สิบเอ็ดบาทถ้วน'],
    ['21.25', 'ยี่สิบเอ็ดบาทยี่สิบห้าสตางค์'],
    ['101.00', 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    ['107.00', 'หนึ่งร้อยเจ็ดบาทถ้วน'],
    ['1070.00', 'หนึ่งพันเจ็ดสิบบาทถ้วน'],
    ['0.50', 'ห้าสิบสตางค์'],
    ['0.01', 'หนึ่งสตางค์'],
    ['1234.50', 'หนึ่งพันสองร้อยสามสิบสี่บาทห้าสิบสตางค์'],
    ['1000000.00', 'หนึ่งล้านบาทถ้วน'],
    ['1000001.00', 'หนึ่งล้านเอ็ดบาทถ้วน'],
    ['2511021.75', 'สองล้านห้าแสนหนึ่งหมื่นหนึ่งพันยี่สิบเอ็ดบาทเจ็ดสิบห้าสตางค์'],
    ['21000000.00', 'ยี่สิบเอ็ดล้านบาทถ้วน'],
  ])('reads %s as %s', (amount, words) => {
    expect(bahtText(amount)).toBe(words);
  });

  it('reads large numbers group by group', () => {
    expect(thaiNumber(1_000_000_000_000n)).toBe('หนึ่งล้านล้าน');
    expect(thaiNumber(10n)).toBe('สิบ');
    expect(() => bahtText('12,00')).toThrow(RangeError);
  });

  it('prints dates in the Buddhist era', () => {
    expect(thaiDate('2026-10-05')).toBe('5 ตุลาคม 2569');
    expect(thaiDate('2027-01-31')).toBe('31 มกราคม 2570');
    expect(thaiMonth('2026-12')).toBe('ธันวาคม 2569');
  });
});
