import { randomUUID } from 'node:crypto';

import { type UserActor } from '@common/context/actor';
import { decodeCursor, encodeCursor } from '@common/pagination/pagination';
import { AppConfig } from '@config/app-config';
import { PrismaService } from '@database/prisma.service';
import { type AuditCategory, type AuditOutcome, type Prisma } from '@generated/prisma/client';
import { OBJECT_STORAGE, type ObjectStorage } from '@integrations/s3/object-storage.port';
import { Inject, Injectable } from '@nestjs/common';

import { AuditService } from './audit.service';

export interface AuditFilter {
  category?: AuditCategory;
  outcome?: AuditOutcome;
  action?: string;
  resourceType?: string;
  resourceId?: string;
  actorId?: string;
  from?: Date;
  to?: Date;
}

const AUDIT_INCLUDE = {
  actorUser: { select: { publicId: true, displayName: true } },
  actorApiClient: { select: { publicId: true, name: true } },
  onBehalfOf: { select: { publicId: true, displayName: true } },
} satisfies Prisma.AuditLogInclude;
export type AuditRow = Prisma.AuditLogGetPayload<{ include: typeof AUDIT_INCLUDE }>;

/** Rows per export; larger periods are exported in several files (auditor PBC packs arrive in B5.6). */
export const EXPORT_MAX_ROWS = 50_000;
const EXPORT_URL_TTL_SECONDS = 5 * 60;

/**
 * Reading and exporting the audit log (B1.3 "Audit", `accounting-design.md` §8 audit trail).
 * Every export is itself audited (`export.generated`).
 */
@Injectable()
export class AuditQueryService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly config: AppConfig,
    private readonly audit: AuditService,
    @Inject(OBJECT_STORAGE) private readonly storage: ObjectStorage,
  ) {}

  async list(filter: AuditFilter, cursor: string | undefined, limit: number) {
    const position = cursor ? decodeCursor(cursor) : undefined;
    const where = await this.where(filter);
    if (position) {
      const at = new Date(String(position['at']));
      const id = BigInt(String(position['id']));
      where.AND = [{ OR: [{ occurredAt: { lt: at } }, { occurredAt: at, id: { lt: id } }] }];
    }
    const rows = await this.prisma.auditLog.findMany({
      where,
      include: AUDIT_INCLUDE,
      orderBy: [{ occurredAt: 'desc' }, { id: 'desc' }],
      take: limit + 1,
    });
    const page = rows.slice(0, limit);
    const last = rows.length > limit ? page.at(-1) : undefined;
    return {
      rows: page,
      nextCursor: last ? encodeCursor({ at: last.occurredAt.toISOString(), id: last.id.toString() }) : null,
    };
  }

  /** CSV of the filtered rows, stored as a transient file; returns a signed download URL. */
  async export(
    actor: UserActor,
    filter: AuditFilter,
  ): Promise<{ fileId: string; url: string; rows: number; truncated: boolean; expiresAt: Date }> {
    const rows = await this.prisma.auditLog.findMany({
      where: await this.where(filter),
      include: AUDIT_INCLUDE,
      orderBy: [{ occurredAt: 'asc' }, { id: 'asc' }],
      take: EXPORT_MAX_ROWS + 1,
    });
    const truncated = rows.length > EXPORT_MAX_ROWS;
    const body = Buffer.from(`\uFEFF${toCsv(rows.slice(0, EXPORT_MAX_ROWS))}`, 'utf8');
    const now = new Date();
    const file = await this.prisma.fileObject.create({
      data: {
        bucket: this.config.get('S3_BUCKET'),
        storageKey: `pending/${randomUUID()}`,
        originalName: `audit-log-${now.toISOString().slice(0, 10)}.csv`,
        mimeType: 'text/csv',
        sizeBytes: BigInt(body.length),
        uploadStatus: 'uploaded',
        // Generated by the system from its own data: nothing to scan.
        scanStatus: 'clean',
        scannedAt: now,
        retentionClass: 'transient',
        ownerUserId: actor.userId,
        createdById: actor.userId,
      },
    });
    const storageKey = `transient/${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, '0')}/${file.publicId}`;
    await this.storage.put(storageKey, body, 'text/csv; charset=utf-8');
    await this.prisma.fileObject.update({ where: { id: file.id }, data: { storageKey } });
    await this.audit.recordStandalone({
      category: 'export',
      action: 'export.generated',
      actor,
      resourceType: 'audit_log',
      data: {
        filter: { ...filter },
        rows: Math.min(rows.length, EXPORT_MAX_ROWS),
        truncated,
        fileId: file.publicId,
      },
    });
    const url = await this.storage.presignGet(storageKey, {
      expiresInSeconds: EXPORT_URL_TTL_SECONDS,
      fileName: file.originalName,
      contentType: 'text/csv',
    });
    return {
      fileId: file.publicId,
      url,
      rows: Math.min(rows.length, EXPORT_MAX_ROWS),
      truncated,
      expiresAt: new Date(now.getTime() + EXPORT_URL_TTL_SECONDS * 1000),
    };
  }

  private async where(filter: AuditFilter): Promise<Prisma.AuditLogWhereInput> {
    const actor = filter.actorId
      ? await this.prisma.user.findUnique({ where: { publicId: filter.actorId }, select: { id: true } })
      : null;
    return {
      ...(filter.category && { category: filter.category }),
      ...(filter.outcome && { outcome: filter.outcome }),
      ...(filter.action && { action: filter.action }),
      ...(filter.resourceType && { resourceType: filter.resourceType }),
      ...(filter.resourceId && { resourcePublicId: filter.resourceId }),
      ...(filter.actorId && { actorUserId: actor?.id ?? -1n }),
      ...((filter.from || filter.to) && {
        occurredAt: { ...(filter.from && { gte: filter.from }), ...(filter.to && { lt: filter.to }) },
      }),
    };
  }
}

const CSV_COLUMNS = [
  'occurred_at',
  'category',
  'action',
  'outcome',
  'actor_type',
  'actor_id',
  'actor_name',
  'on_behalf_of',
  'resource_type',
  'resource_id',
  'request_id',
  'data',
];

export function csvCell(value: unknown): string {
  const text =
    value === null || value === undefined ? '' : typeof value === 'string' ? value : JSON.stringify(value);
  // Neutralise spreadsheet formulas (CSV injection) and quote every cell.
  const safe = /^[=+\-@\t\r]/.test(text) ? `'${text}` : text;
  return `"${safe.replace(/"/g, '""')}"`;
}

export function toCsv(rows: AuditRow[]): string {
  const lines = rows.map((r) =>
    [
      r.occurredAt.toISOString(),
      r.category,
      r.action,
      r.outcome,
      r.actorType,
      r.actorUser?.publicId ?? r.actorApiClient?.publicId ?? '',
      r.actorUser?.displayName ?? r.actorApiClient?.name ?? '',
      r.onBehalfOf?.publicId ?? '',
      r.resourceType,
      r.resourcePublicId,
      r.requestId,
      r.data,
    ]
      .map(csvCell)
      .join(','),
  );
  return [CSV_COLUMNS.join(','), ...lines].join('\r\n') + '\r\n';
}
