import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  FOLDING_CALCULATOR_VERSION,
  foldingCalculator,
  type FoldingResult,
} from '@modules/pricing/calculators/folding/folding-calculator';

import { CASES, type GoldenCase } from '../golden/folding/cases';

/**
 * Golden folding cases (B2.3): each case's result must stay within 0.005 of `test/golden/folding/<id>.json`.
 * `UPDATE_GOLDEN=1` rewrites the files and `docs/pricing-validation-folding.md` — only after a reviewed change.
 */

const DIR = join(__dirname, '..', 'golden', 'folding');
const DOC = join(__dirname, '..', '..', 'docs', 'pricing-validation-folding.md');
const TOLERANCE = 0.005;
const update = process.env['UPDATE_GOLDEN'] === '1';

type Summary = ReturnType<typeof summarise>;

function summarise(result: FoldingResult) {
  return {
    selection: result.selection,
    options: result.options.map((o) => ({
      optionKey: o.optionKey,
      error: o.error ? `${o.error.code}: ${o.error.detail}` : null,
      steps: o.steps.map((s) =>
        s
          ? {
              qty: s.qty,
              productionRun: s.boxAmount,
              buyPrice: s.buyPrice,
              perPcs: s.perPcs,
              sum: s.sum,
              vatPrice: s.vatPrice,
              designFee: s.designFee,
              structureDesignFee: s.structureDesignFee,
              total: s.total,
              leadTimeDays: s.leadTimeDays,
              marginPct: s.marginPct,
              parts: s.parts.map((p) => ({
                partKey: p.partKey,
                sheet: p.layout.layout.sheet.sheetKey,
                layoutStandard: p.layout.layout.layoutStandard,
                layoutAmount: p.layout.layout.layoutAmount,
                pressSheets: p.layout.waste.totalSheets,
                cost: p.layout.totalCost,
                buyPrice: p.buyPrice,
                targetMarginPct: p.forSale.targetMarginPct,
                perPcs: p.forSale.perPcs,
              })),
            }
          : null,
      ),
    })),
  };
}

function compare(actual: unknown, expected: unknown, path: string, errors: string[]): void {
  if (typeof expected === 'number' && typeof actual === 'number') {
    if (Math.abs(actual - expected) > TOLERANCE) errors.push(`${path}: ${actual} ≠ ${expected}`);
    return;
  }
  if (Array.isArray(expected) && Array.isArray(actual)) {
    if (actual.length !== expected.length)
      errors.push(`${path}: length ${actual.length} ≠ ${expected.length}`);
    expected.forEach((e, i) => compare(actual[i], e, `${path}[${i}]`, errors));
    return;
  }
  if (expected && typeof expected === 'object' && actual && typeof actual === 'object') {
    for (const [k, v] of Object.entries(expected))
      compare((actual as Record<string, unknown>)[k], v, `${path}.${k}`, errors);
    return;
  }
  if (actual !== expected) errors.push(`${path}: ${JSON.stringify(actual)} ≠ ${JSON.stringify(expected)}`);
}

const money = (n: number) => n.toFixed(2);
const replacer = (_: string, value: unknown) => (value instanceof Set ? [...value] : value);

function renderDoc(results: { c: GoldenCase; s: Summary }[]): string {
  const lines: string[] = [
    '# Folding pricing — validation cases (B2.3)',
    '',
    '> **Status: pending business sign-off.** Generated by `UPDATE_GOLDEN=1 pnpm test -- folding-golden` from',
    '> `test/golden/folding/cases.ts`; do not edit by hand. Calculator version ' +
      '`' +
      FOLDING_CALCULATOR_VERSION +
      '`.',
    '',
    '## How these were derived and how to sign them off',
    '- No Locopack dump with calculator **outputs** exists (`test/fixtures/legacy/calculate_logs_*.sql` holds inputs only), so the',
    "  prompt's fallback applies. Every formula is ported function by function with `legacy:` line references; the unit tests",
    '  (`src/modules/pricing/calculators/folding/**/*.spec.ts`) check each component against values worked out by hand from the PHP.',
    '- The 20 cases below price complete, **made-up** price lists (no real supplier data, D-005). To sign off, the business team',
    '  enters the same price rows for a test factory in a Locopack staging copy, runs the CS folding calculator with the same',
    '  configuration, and compares the per-piece price and total. Expect sub-satang differences where Locopack stores prices as',
    '  `FLOAT` (float32) and Packio as exact decimals.',
    '- Known, intended differences from Locopack (port map `docs/legacy/05-folding-port-map.md` §5): Q1 an option is complete only',
    '  when every part is; Q2 design fees once per quote; Q3 VAT from the dated rate; Q6 process exclusions enforced; Q9/Q10 no',
    '  caches, deterministic first match; Q11 legacy factory ids replaced by terms; Q12 no thousands-comma truncation; Q13 flip',
    '  sheets work; Q14/Q16 missing data refuses the configuration instead of pricing with 0; Q17 finish-2 waste by position;',
    "  Q19 4-colour price from the factory's own list; Q20 open NULL bounds; engine B and shipping are not part of B2.3.",
    '',
    '| Business sign-off | Name | Date |',
    '|---|---|---|',
    '| Pricing owner | | |',
    '| Finance | | |',
    '',
  ];
  for (const { c, s } of results) {
    lines.push(`## ${c.id} — ${c.title}`, '', `Legacy: ${c.legacy.map((l) => '`' + l + '`').join(', ')}`, '');
    lines.push(
      '| Option | Qty | Run | Layout | Press sheets | Buy price | Per piece (VAT incl.) | Total (VAT incl.) | Lead time |',
      '|---|---|---|---|---|---|---|---|---|',
    );
    for (const o of s.options) {
      if (o.error) {
        lines.push(`| ${o.optionKey} | — | — | — | — | ${o.error} | — | — | — |`);
        continue;
      }
      o.steps.forEach((st, i) => {
        if (!st) {
          lines.push(`| ${o.optionKey} | ${c.input.quantities[i]} | — | no layout | — | — | — | — | — |`);
          return;
        }
        const p = st.parts
          .map((x) => `${x.sheet} ${x.layoutStandard ? 'std' : 'rot'} ×${x.layoutAmount}`)
          .join('; ');
        const sheets = st.parts.map((x) => x.pressSheets).join('; ');
        lines.push(
          `| ${o.optionKey} | ${st.qty} | ${st.productionRun} | ${p} | ${sheets} | ${money(st.buyPrice)} | ${money(st.perPcs)} | ${money(st.total)} | ${st.leadTimeDays} d |`,
        );
      });
    }
    lines.push('', `Selected per quantity: ${s.selection.map((x) => x ?? 'none').join(', ')}`, '');
    lines.push('<details><summary>Configuration and price rows</summary>', '', '```json');
    lines.push(JSON.stringify({ input: c.input, options: c.options }, replacer, 2));
    lines.push('```', '', '</details>', '');
  }
  return lines.join('\n');
}

describe('folding golden cases (B2.3)', () => {
  const results = CASES.map((c) => ({
    c,
    s: summarise(foldingCalculator.calculate(c.input, { options: c.options })),
  }));

  if (update) {
    for (const { c, s } of results)
      writeFileSync(join(DIR, `${c.id}.json`), JSON.stringify(s, null, 2) + '\n');
    writeFileSync(DOC, renderDoc(results));
  }

  it('has 20 cases, every one priced', () => {
    expect(CASES).toHaveLength(20);
    for (const { c, s } of results) {
      expect([c.id, s.selection.every((x) => x !== null)]).toEqual([c.id, true]);
    }
  });

  it.each(results.map((r) => [r.c.id, r] as const))(
    '%s matches its golden file within 0.005',
    (_id, { c, s }) => {
      const expected = JSON.parse(readFileSync(join(DIR, `${c.id}.json`), 'utf8')) as Summary;
      const errors: string[] = [];
      compare(s, expected, c.id, errors);
      expect(errors).toEqual([]);
    },
  );
});
