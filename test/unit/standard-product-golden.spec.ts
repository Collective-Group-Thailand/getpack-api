import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  STANDARD_PRODUCT_CALCULATOR_VERSION,
  standardProductCalculator,
  type StandardProductInput,
  type StandardProductOption,
  type StandardProductOptionResult,
} from '@modules/pricing/calculators/standard-product/standard-product-calculator';

/**
 * Golden standard-product cases (U-B6 standard product). The inputs and the expected values are in `test/golden/standard-product/golden.json`,
 * written by `test/golden/standard-product/cases.py`: the expected values come from the independent Python transcription of the
 * PHP (`reference/standard_reference.py`), not from this port. Every number must agree within 1e-6. `UPDATE_GOLDEN=1`
 * (with `--testPathPatterns standard-product-golden`) rewrites `docs/pricing-validation-standard-product.md` from the port's results; the
 * expected values change only by rerunning the Python.
 */

const DIR = join(__dirname, '..', 'golden', 'standard-product');
const DOC = join(__dirname, '..', '..', 'docs', 'pricing-validation-standard-product.md');
const TOLERANCE = 1e-6;
const update = process.env['UPDATE_GOLDEN'] === '1';

/** The business sign-off (`test/golden/standard-product/sign-off.json`), tied to the calculator version and the cases. */
interface SignOff {
  calculatorVersion: string;
  goldenSha256: string;
  evidence: string;
  signatures: { role: string; name: string; date: string }[];
}
const SIGN_OFF = join(DIR, 'sign-off.json');
const signOff: SignOff | null = existsSync(SIGN_OFF)
  ? (JSON.parse(readFileSync(SIGN_OFF, 'utf8')) as SignOff)
  : null;
const goldenSha256 = createHash('sha256')
  .update(readFileSync(join(DIR, 'golden.json')))
  .digest('hex');
const signedOff =
  signOff !== null &&
  signOff.calculatorVersion === STANDARD_PRODUCT_CALCULATOR_VERSION &&
  signOff.goldenSha256 === goldenSha256 &&
  ['Pricing owner', 'Finance'].every((role) => signOff.signatures.some((s) => s.role === role));

interface GoldenCase {
  key: string;
  title: string;
  input: StandardProductInput;
  options: StandardProductOption[];
  expected: unknown;
}

type Summary = ReturnType<typeof summarise>;

function summarise(options: StandardProductOptionResult[]) {
  const text = (e: { code: string; detail: string } | null) => (e ? `${e.code}: ${e.detail}` : null);
  return options.map((o) => ({
    optionKey: o.optionKey,
    error: text(o.error),
    errors: o.stepErrors.map(text),
    steps: o.steps.map((s) =>
      s
        ? {
            qty: s.qty,
            tierMin: s.tier.min,
            tierMax: s.tier.max,
            targetMarginPct: s.targetMarginPct,
            withMargin: s.tier.withMargin,
            perPcs: s.perPcs,
            buyPrice: s.buyPrice,
            sum: s.sum,
            designFee: s.designFee,
            total: s.total,
            leadTimeDays: s.leadTimeDays,
          }
        : null,
    ),
    tiers: o.tiers ? o.tiers.map((t) => ({ min: t.min, max: t.max, perPcs: t.perPcs })) : null,
  }));
}

function compare(actual: unknown, expected: unknown, path: string, errors: string[]): void {
  if (typeof expected === 'number' && typeof actual === 'number') {
    if (Math.abs(actual - expected) > TOLERANCE) errors.push(`${path}: ${actual} ≠ ${expected}`);
    return;
  }
  if (Array.isArray(expected) && Array.isArray(actual)) {
    if (actual.length !== expected.length)
      errors.push(`${path}: length ${actual.length} ≠ ${expected.length}`);
    expected.forEach((e, i) => compare(actual[i], e, `${path}[${i}]`, errors));
    return;
  }
  if (expected && typeof expected === 'object' && actual && typeof actual === 'object') {
    for (const [k, v] of Object.entries(expected))
      compare((actual as Record<string, unknown>)[k], v, `${path}.${k}`, errors);
    return;
  }
  if (actual !== expected) errors.push(`${path}: ${JSON.stringify(actual)} ≠ ${JSON.stringify(expected)}`);
}

const money = (n: number) => n.toFixed(2);

function renderDoc(results: { c: GoldenCase; s: Summary }[]): string {
  const range = (min: number | null, max: number | null) => `${min ?? '…'}–${max ?? '…'}`;
  const lines: string[] = [
    '# Standard product pricing — validation cases (U-B6)',
    '',
    (signedOff
      ? `> **Status: signed off** (${signOff.signatures.map((x) => `${x.role} ${x.date}`).join(', ')}).`
      : '> **Status: pending business sign-off.**') +
      ' Generated by `UPDATE_GOLDEN=1` with `--testPathPatterns standard-product-golden` from',
    '> `test/golden/standard-product/golden.json`; do not edit by hand. Calculator version `' +
      STANDARD_PRODUCT_CALCULATOR_VERSION +
      '`.',
    '',
    '## How these were derived and how to sign them off',
    '- No Locopack dump with standard-product calculations exists (legacy writes no `calculate_logs` for them). The expected',
    '  values were derived twice, independently, from the PHP: once by the TypeScript port and once by a Python',
    '  transcription that keeps the PHP statement order (`test/golden/standard-product/reference/standard_reference.py`:',
    '  `getSteps`, `sortPrices`, `findPrice`, `costToSalePrice`, `calculateMargin`, `calculateVat`). The two agree on every',
    "  number below within 1e-6 (`test/unit/standard-product-golden.spec.ts`); cases 07–09 also reproduce the port map's",
    '  hand-derived G1–G3.',
    '- The 20 cases price complete, **made-up** price lists (no real supplier data, D-005). To sign off, the business team',
    "  enters the same tiers for a test SKU in a Locopack staging copy (`standard_product_prices`, the factory's",
    '  `factory_match_print_type` for print type 9 with the margin and fix cost), opens the CS standard-product screen and',
    '  compares the price per piece **before delivery** (`per_pcs`) of each tier.',
    '- Known, intended differences from Locopack (port map `docs/legacy/05-standard-product-port-map.md` §9): the tier price',
    "  is the goods price — delivery is its own quote line (D-013), so legacy's delivery per piece (at the tier minimum or",
    "  10 000) is not in it and the tier merging (`sortPrices`) compares goods prices; getpack's `standard_product` sell table",
    '  (margin by quantity, fix cost per piece, design fee) and the dated VAT rate instead of `locopack_margin` /',
    '  `locopack_fix_cost` and `SALE_MARGIN_VAT`; a quantity outside every tier, a missing margin or a missing price line',
    '  refuses the factory instead of failing the request; several factories may price one SKU.',
    '- **For the business to decide** (kept from legacy, quirk S8): a later tier whose price is not lower absorbs the',
    '  earlier ranges **at its own, higher price** (cases 05, 06).',
    '',
    '| Business sign-off | Name | Date |',
    '|---|---|---|',
    ...['Pricing owner', 'Finance'].map((role) => {
      const x = signedOff ? signOff.signatures.find((y) => y.role === role) : undefined;
      return `| ${role} | ${x?.name ?? ''} | ${x?.date ?? ''} |`;
    }),
    ...(signedOff ? ['', `Evidence: ${signOff.evidence}`] : []),
    '',
  ];
  for (const { c, s } of results) {
    lines.push(`## ${c.key} — ${c.title}`, '');
    for (const o of s) {
      if (o.tiers) {
        lines.push(
          `Tiers of ${o.optionKey}: ` +
            o.tiers.map((t) => `${range(t.min, t.max)} → ${money(t.perPcs)}`).join(' · '),
          '',
        );
      }
    }
    lines.push(
      '| Option | Qty | Tier | Margin | Buy price | Per piece (VAT incl.) | Total (VAT incl.) | Lead time |',
      '|---|---|---|---|---|---|---|---|',
    );
    for (const o of s) {
      if (o.error) {
        lines.push(`| ${o.optionKey} | — | ${o.error} | — | — | — | — | — |`);
        continue;
      }
      o.steps.forEach((st, i) => {
        if (!st) {
          lines.push(`| ${o.optionKey} | ${c.input.quantities[i]} | ${o.errors[i]} | — | — | — | — | — |`);
          return;
        }
        lines.push(
          `| ${o.optionKey} | ${st.qty} | ${range(st.tierMin, st.tierMax)} | ${st.targetMarginPct} % | ${money(st.buyPrice)} | ${money(st.perPcs)} | ${money(st.total)} | ${st.leadTimeDays} d |`,
        );
      });
    }
    lines.push('', '<details><summary>Configuration and price rows</summary>', '', '```json');
    lines.push(JSON.stringify({ input: c.input, options: c.options }, null, 2));
    lines.push('```', '', '</details>', '');
  }
  return lines.join('\n');
}

describe('standard product golden cases (U-B6 standard product)', () => {
  const cases = JSON.parse(readFileSync(join(DIR, 'golden.json'), 'utf8')) as GoldenCase[];
  const results = cases.map((c) => ({
    c,
    s: summarise(standardProductCalculator.calculate(c.input, { options: c.options }).options),
  }));

  if (update) writeFileSync(DOC, renderDoc(results));

  it('keeps its sign-off current: re-sign after any change to the calculator version or the cases', () => {
    if (signOff === null) return; // not signed yet: the doc says pending
    expect({ calculatorVersion: signOff.calculatorVersion, goldenSha256: signOff.goldenSha256 }).toEqual({
      calculatorVersion: STANDARD_PRODUCT_CALCULATOR_VERSION,
      goldenSha256,
    });
    expect(signedOff).toBe(true);
  });

  it('has 20 cases; all but the three refusal cases price a quantity', () => {
    expect(cases).toHaveLength(20);
    const unpriced = results
      .filter(({ s }) => !s.some((o) => o.steps.some((st) => st !== null)))
      .map((r) => r.c.key);
    expect(unpriced).toEqual(['04-outside-tiers', '11-no-margin', '15-no-lines']);
  });

  it.each(results.map((r) => [r.c.key, r] as const))(
    '%s agrees with the Python transcription of the PHP within 1e-6',
    (_key, { c, s }) => {
      const errors: string[] = [];
      compare(s, c.expected, c.key, errors);
      expect(errors).toEqual([]);
    },
  );
});
