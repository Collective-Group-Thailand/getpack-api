import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  freelancerPayable,
  fromCost,
  fromGross,
  SERVICE_CALCULATOR_VERSION,
  serviceCalculator,
  type ServiceInput,
  type ServiceOption,
} from '@modules/pricing/calculators/service/service-calculator';
import { PricingError } from '@modules/pricing/calculators/shared/pricing-error';

/**
 * Golden service cases (U-B6 service). Inputs and expected values are in `test/golden/service/golden.json`, written by
 * `test/golden/service/cases.py` from the independent transcription of legacy's JavaScript / PHP
 * (`reference/service_reference.py`), not from this port. Every number must agree within 1e-6. `UPDATE_GOLDEN=1` (with
 * `--testPathPatterns service-golden`) rewrites `docs/pricing-validation-service.md` from the port's results.
 */

const DIR = join(__dirname, '..', 'golden', 'service');
const DOC = join(__dirname, '..', '..', 'docs', 'pricing-validation-service.md');
const TOLERANCE = 1e-6;
const update = process.env['UPDATE_GOLDEN'] === '1';

type ManualCase = {
  key: string;
  kind: 'manual';
  title: string;
  input: { basis: 'buy_cost_net' | 'sell_gross'; amount: number; marginPct: number; vatPct: number };
  expected: unknown;
};
type EngineCase = {
  key: string;
  kind: 'engine';
  title: string;
  input: ServiceInput;
  options: ServiceOption[];
  expected: unknown;
};
type GoldenCase = ManualCase | EngineCase;

function manual(c: ManualCase) {
  const { basis, amount, marginPct, vatPct } = c.input;
  try {
    const amounts =
      basis === 'buy_cost_net' ? fromCost(amount, marginPct, vatPct) : fromGross(amount, marginPct, vatPct);
    return {
      error: null,
      amounts,
      freelancerPayable: basis === 'sell_gross' ? freelancerPayable(amount, marginPct, vatPct) : null,
    };
  } catch (error) {
    if (!(error instanceof PricingError)) throw error;
    return { error: `${error.code}: ${error.detail}`, amounts: null, freelancerPayable: null };
  }
}

function engine(c: EngineCase) {
  const text = (e: { code: string; detail: string } | null) => (e ? `${e.code}: ${e.detail}` : null);
  return serviceCalculator.calculate(c.input, { options: c.options }).options.map((o) => ({
    optionKey: o.optionKey,
    error: text(o.error),
    errors: o.stepErrors.map(text),
    steps: o.steps.map((s) =>
      s
        ? {
            qty: s.qty,
            targetMarginPct: s.targetMarginPct,
            perPcs: s.perPcs,
            net: s.unit.net * s.qty,
            buyPrice: s.buyPrice,
            total: s.total,
            vatPrice: s.vatPrice,
            leadTimeDays: s.leadTimeDays,
          }
        : null,
    ),
  }));
}

function compare(actual: unknown, expected: unknown, path: string, errors: string[]): void {
  if (typeof expected === 'number' && typeof actual === 'number') {
    if (Math.abs(actual - expected) > TOLERANCE) errors.push(`${path}: ${actual} ≠ ${expected}`);
    return;
  }
  if (Array.isArray(expected) && Array.isArray(actual)) {
    if (actual.length !== expected.length)
      errors.push(`${path}: length ${actual.length} ≠ ${expected.length}`);
    expected.forEach((e, i) => compare(actual[i], e, `${path}[${i}]`, errors));
    return;
  }
  if (expected && typeof expected === 'object' && actual && typeof actual === 'object') {
    for (const [k, v] of Object.entries(expected))
      compare((actual as Record<string, unknown>)[k], v, `${path}.${k}`, errors);
    return;
  }
  if (actual !== expected) errors.push(`${path}: ${JSON.stringify(actual)} ≠ ${JSON.stringify(expected)}`);
}

const money = (n: number) => n.toFixed(2);

function renderDoc(
  results: { c: GoldenCase; s: ReturnType<typeof manual> | ReturnType<typeof engine> }[],
): string {
  const lines: string[] = [
    '# Service pricing — validation cases (U-B6)',
    '',
    '> **Status: pending business sign-off.** Generated by `UPDATE_GOLDEN=1` with `--testPathPatterns service-golden` from',
    '> `test/golden/service/golden.json`; do not edit by hand. Calculator version `' +
      SERVICE_CALCULATOR_VERSION +
      '`.',
    '',
    '## How these were derived and how to sign them off',
    '- Legacy has **no service calculator**: the only service maths is the CS service page (`cs/service`,',
    '  `service-orders/cs.vue:381-429`), where CS types the cost (or, for design, the VAT-inclusive price) and the browser',
    '  applies the 6.5 % service margin and 7 % VAT, and the PHP designer payable (`calculateServiceCost`). Packio ports',
    '  exactly that (port map `docs/legacy/05-service-port-map.md` §9, D-194). The expected values come from an independent',
    '  transcription of the JavaScript and PHP (`test/golden/service/reference/service_reference.py`); the port agrees within',
    '  1e-6 (`test/unit/service-golden.spec.ts`).',
    '- Cases 01–20 are amounts CS enters; cases 21–24 a factory service price line (made-up, D-005). To sign off, the',
    '  business team enters the same amounts on the Locopack staging `cs/service` page (margin 6.5 %, or the one stated) and',
    '  compares the net, VAT, gross and cost; and checks the designer payable (`orders.design_cost`) of a hired design.',
    "- Known, intended differences from Locopack: the margin is Packio's `service` sell table and VAT the dated rate (legacy",
    '  config and a 1.07 literal); the server computes the amounts (legacy trusted the browser and let CS edit the result,',
    '  V2, V3); a factory line makes a service instant and multiplies by the quantity (legacy quantity 1); a service quote',
    '  has no shipping line; the browser (half-up) and PHP (ceiling) roundings are both kept where legacy used them (V4).',
    '',
    '| Business sign-off | Name | Date |',
    '|---|---|---|',
    '| Pricing owner | | |',
    '| Finance | | |',
    '',
    '## Amounts CS enters',
    '',
    '| Case | Input | Margin | Net | VAT | Gross | Cost | Margin amount | Freelancer payable |',
    '|---|---|---|---|---|---|---|---|---|',
  ];
  for (const { c, s } of results) {
    if (c.kind !== 'manual') continue;
    const r = s as ReturnType<typeof manual>;
    const input = `${c.input.basis === 'sell_gross' ? 'sell' : 'cost'} ${money(c.input.amount)}`;
    if (!r.amounts) {
      lines.push(
        `| ${c.key} — ${c.title} | ${input} | ${c.input.marginPct} % | ${r.error} | — | — | — | — | — |`,
      );
      continue;
    }
    const a = r.amounts;
    lines.push(
      `| ${c.key} — ${c.title} | ${input} | ${c.input.marginPct} % | ${money(a.net)} | ${money(a.vat)} | ${money(a.gross)} | ${money(a.cost)} | ${money(a.margin)} | ${r.freelancerPayable === null ? '—' : money(r.freelancerPayable)} |`,
    );
  }
  lines.push('', '## A factory service price line', '');
  lines.push(
    '| Case | Option | Qty | Margin | Per unit (VAT incl.) | Total (VAT incl.) | Buy price | Lead time |',
    '|---|---|---|---|---|---|---|---|',
  );
  for (const { c, s } of results) {
    if (c.kind !== 'engine') continue;
    for (const o of s as ReturnType<typeof engine>) {
      o.steps.forEach((st, i) => {
        lines.push(
          st
            ? `| ${c.key} — ${c.title} | ${o.optionKey} | ${st.qty} | ${st.targetMarginPct} % | ${money(st.perPcs)} | ${money(st.total)} | ${money(st.buyPrice)} | ${st.leadTimeDays} d |`
            : `| ${c.key} — ${c.title} | ${o.optionKey} | ${c.input.quantities[i]} | ${o.errors[i]} | — | — | — | — |`,
        );
      });
    }
  }
  lines.push('');
  return lines.join('\n');
}

describe('service golden cases (U-B6 service)', () => {
  const cases = JSON.parse(readFileSync(join(DIR, 'golden.json'), 'utf8')) as GoldenCase[];
  const results = cases.map((c) => ({ c, s: c.kind === 'manual' ? manual(c) : engine(c) }));
  if (update) writeFileSync(DOC, renderDoc(results));

  it('has 20 amounts CS enters and 4 price-line cases', () => {
    expect(cases.filter((c) => c.kind === 'manual')).toHaveLength(20);
    expect(cases.filter((c) => c.kind === 'engine')).toHaveLength(4);
  });

  it.each(results.map((r) => [r.c.key, r] as const))(
    '%s agrees with the transcription of the JavaScript / PHP within 1e-6',
    (_key, { c, s }) => {
      const errors: string[] = [];
      compare(s, c.expected, c.key, errors);
      expect(errors).toEqual([]);
    },
  );
});
