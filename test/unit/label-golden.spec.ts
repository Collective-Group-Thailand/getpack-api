import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  LABEL_CALCULATOR_VERSION,
  labelCalculator,
  type LabelInput,
  type LabelOption,
  type LabelOptionResult,
} from '@modules/pricing/calculators/label/label-calculator';

/**
 * Golden label cases (U-B6 label). The inputs and the expected values are in `test/golden/label/golden.json`,
 * written by `test/golden/label/cases.py`: the expected values come from the independent Python transcription of the
 * PHP (`reference/label_reference.py`), not from this port. Every number must agree within 1e-6. `UPDATE_GOLDEN=1`
 * rewrites `docs/pricing-validation-label.md` from the port's results; the expected values change only by rerunning
 * the Python.
 */

const DIR = join(__dirname, '..', 'golden', 'label');
const DOC = join(__dirname, '..', '..', 'docs', 'pricing-validation-label.md');
const TOLERANCE = 1e-6;
const update = process.env['UPDATE_GOLDEN'] === '1';

/** The business sign-off (`test/golden/label/sign-off.json`), tied to the calculator version and the cases. */
interface SignOff {
  calculatorVersion: string;
  goldenSha256: string;
  evidence: string;
  signatures: { role: string; name: string; date: string }[];
}
const SIGN_OFF = join(DIR, 'sign-off.json');
const signOff: SignOff | null = existsSync(SIGN_OFF)
  ? (JSON.parse(readFileSync(SIGN_OFF, 'utf8')) as SignOff)
  : null;
const goldenSha256 = createHash('sha256')
  .update(readFileSync(join(DIR, 'golden.json')))
  .digest('hex');
const signedOff =
  signOff !== null &&
  signOff.calculatorVersion === LABEL_CALCULATOR_VERSION &&
  signOff.goldenSha256 === goldenSha256 &&
  ['Pricing owner', 'Finance'].every((role) => signOff.signatures.some((s) => s.role === role));

type JsonOption = Omit<LabelOption, 'inkColours'> & { inkColours: string[] };
interface GoldenCase {
  key: string;
  title: string;
  input: LabelInput;
  options: JsonOption[];
  expected: unknown;
}

type Summary = ReturnType<typeof summarise>;

function summarise(options: LabelOptionResult[]) {
  return options.map((o) => ({
    optionKey: o.optionKey,
    error: o.error?.code ?? null,
    errors: o.stepErrors.map((e) => e?.code ?? null),
    steps: o.steps.map((s) =>
      s
        ? {
            qty: s.qty,
            layoutAmount: s.layout.layoutAmount,
            standard: s.layout.standard,
            roll: s.layout.roll,
            sheetWIn: s.layout.sheet.sheetWIn,
            sheetLIn: s.layout.sheet.sheetLIn,
            sheets: s.layout.waste?.total ?? null,
            costTotal: s.cost.total,
            factoryPricePerPcs: s.factoryPricePerPcs,
            buyPrice: s.buyPrice,
            perPcs: s.forSale.perPcs,
            sum: s.forSale.sum,
            vatPrice: s.forSale.vatPrice,
            designFee: s.designFee,
            total: s.total,
            leadTimeDays: s.leadTimeDays,
            marginPct: s.marginPct,
          }
        : null,
    ),
  }));
}

function compare(actual: unknown, expected: unknown, path: string, errors: string[]): void {
  if (typeof expected === 'number' && typeof actual === 'number') {
    if (Math.abs(actual - expected) > TOLERANCE) errors.push(`${path}: ${actual} ≠ ${expected}`);
    return;
  }
  if (Array.isArray(expected) && Array.isArray(actual)) {
    if (actual.length !== expected.length)
      errors.push(`${path}: length ${actual.length} ≠ ${expected.length}`);
    expected.forEach((e, i) => compare(actual[i], e, `${path}[${i}]`, errors));
    return;
  }
  if (expected && typeof expected === 'object' && actual && typeof actual === 'object') {
    for (const [k, v] of Object.entries(expected))
      compare((actual as Record<string, unknown>)[k], v, `${path}.${k}`, errors);
    return;
  }
  if (actual !== expected) errors.push(`${path}: ${JSON.stringify(actual)} ≠ ${JSON.stringify(expected)}`);
}

const money = (n: number) => n.toFixed(2);

function renderDoc(results: { c: GoldenCase; s: Summary }[]): string {
  const lines: string[] = [
    '# Label pricing — validation cases (U-B6)',
    '',
    (signedOff
      ? `> **Status: signed off** (${signOff.signatures.map((x) => `${x.role} ${x.date}`).join(', ')}).`
      : '> **Status: pending business sign-off.**') +
      ' Generated by `UPDATE_GOLDEN=1 pnpm test -- label-golden` from',
    '> `test/golden/label/golden.json`; do not edit by hand. Calculator version `' +
      LABEL_CALCULATOR_VERSION +
      '`.',
    '',
    '## How these were derived and how to sign them off',
    '- No Locopack dump with calculator **outputs** exists (`test/fixtures/legacy/calculate_logs_*.sql` holds label inputs',
    '  only). The expected values were therefore derived twice, independently, from the PHP: once by the TypeScript port and',
    '  once by a Python transcription that keeps the PHP statement order (`test/golden/label/reference/label_reference.py`:',
    '  `calLayoutAmount`, `calculateLayouts`, `calculateWaste`, the digital `calculateCost`, the factory margin, the CS',
    '  selection and `SaleMargin`). The two agree on every number below within 1e-6 (`test/unit/label-golden.spec.ts`).',
    '- The 20 cases price complete, **made-up** price lists (no real supplier data, D-005). To sign off, the business team',
    '  enters the same rows for a test factory in a Locopack staging copy, runs the CS label calculator (`/api/cs/label`)',
    '  with the same configuration, and compares the factory price per piece, the per-piece price and the total. Expect',
    '  sub-satang differences where Locopack stores prices as `FLOAT` (float32) and Packio as exact decimals.',
    '- Known, intended differences from Locopack (port map `docs/legacy/05-label-port-map.md` §5): L1 every quantity on its',
    '  own material; L2 **offset label printing is not priced** (legacy never produced an offset label price — the business',
    '  decides at sign-off whether offset is offered); L3 the minimum order per quantity; L7 the no-die-cut factories and',
    '  L13 the shortest roll as print-type terms; L12 an explicit, stable lay-out order; L15 a missing finish, die-cut,',
    '  material or die-block row refuses the option instead of failing the request. Shipping is its own quote line (D-013),',
    '  so no delivery is included here. The label is priced on its W × L bounding box, as legacy.',
    '',
    '| Business sign-off | Name | Date |',
    '|---|---|---|',
    ...['Pricing owner', 'Finance'].map((role) => {
      const x = signedOff ? signOff.signatures.find((y) => y.role === role) : undefined;
      return `| ${role} | ${x?.name ?? ''} | ${x?.date ?? ''} |`;
    }),
    ...(signedOff ? ['', `Evidence: ${signOff.evidence}`] : []),
    '',
  ];
  for (const { c, s } of results) {
    lines.push(`## ${c.key} — ${c.title}`, '');
    lines.push(
      '| Option | Qty | Lay-out | Factory price / pc | Buy price | Per piece (VAT incl.) | Total (VAT incl.) | Lead time |',
      '|---|---|---|---|---|---|---|---|',
    );
    for (const o of s) {
      if (o.error) {
        lines.push(`| ${o.optionKey} | — | — | ${o.error} | — | — | — | — |`);
        continue;
      }
      o.steps.forEach((st, i) => {
        if (!st) {
          lines.push(`| ${o.optionKey} | ${c.input.quantities[i]} | ${o.errors[i]} | — | — | — | — | — |`);
          return;
        }
        const how = st.roll
          ? `roll ${st.sheetWIn}″ (${st.layoutAmount} labels)`
          : `sheet ${st.sheetWIn}×${st.sheetLIn}″, ${st.layoutAmount} per sheet${st.standard ? '' : ' (rotated)'}, ${st.sheets} sheets`;
        lines.push(
          `| ${o.optionKey} | ${st.qty} | ${how} | ${money(st.factoryPricePerPcs)} | ${money(st.buyPrice)} | ${money(st.perPcs)} | ${money(st.total)} | ${st.leadTimeDays} d |`,
        );
      });
    }
    lines.push('', '<details><summary>Configuration and price rows</summary>', '', '```json');
    lines.push(JSON.stringify({ input: c.input, options: c.options }, null, 2));
    lines.push('```', '', '</details>', '');
  }
  return lines.join('\n');
}

describe('label golden cases (U-B6 label)', () => {
  const cases = JSON.parse(readFileSync(join(DIR, 'golden.json'), 'utf8')) as GoldenCase[];
  const results = cases.map((c) => ({
    c,
    s: summarise(
      labelCalculator.calculate(c.input, {
        options: c.options.map((o) => ({ ...o, inkColours: new Set(o.inkColours) })),
      }).options,
    ),
  }));

  if (update) writeFileSync(DOC, renderDoc(results));

  it('keeps its sign-off current: re-sign after any change to the calculator version or the cases', () => {
    if (signOff === null) return; // not signed yet: the doc says pending
    expect({ calculatorVersion: signOff.calculatorVersion, goldenSha256: signOff.goldenSha256 }).toEqual({
      calculatorVersion: LABEL_CALCULATOR_VERSION,
      goldenSha256,
    });
    expect(signedOff).toBe(true);
  });

  it('has 20 cases; all but the three refusal cases price a quantity', () => {
    expect(cases).toHaveLength(20);
    const unpriced = results
      .filter(({ s }) => !s.some((o) => o.steps.some((st) => st !== null)))
      .map((r) => r.c.key);
    expect(unpriced).toEqual(['14-offset-refused', '15-colour-not-printed', '16-finish-missing']);
  });

  it.each(results.map((r) => [r.c.key, r] as const))(
    '%s agrees with the Python transcription of the PHP within 1e-6',
    (_key, { c, s }) => {
      const errors: string[] = [];
      compare(s, c.expected, c.key, errors);
      expect(errors).toEqual([]);
    },
  );
});
