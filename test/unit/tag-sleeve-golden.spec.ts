import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { type FoldingResult } from '@modules/pricing/calculators/folding/folding-calculator';
import {
  TAG_SLEEVE_CALCULATOR_VERSION,
  tagSleeveCalculator,
} from '@modules/pricing/calculators/tag-sleeve/tag-sleeve-calculator';

import { CASES, type GoldenCase } from '../golden/tag-sleeve/cases';

/**
 * Golden tag & sleeve cases (U-B6 tag & sleeve): each case's result must stay within 0.005 of
 * `test/golden/tag-sleeve/<id>.json`. `UPDATE_GOLDEN=1` rewrites the files and `docs/pricing-validation-tag-sleeve.md`
 * — only after a reviewed change, and restricted to this spec (`--testPathPatterns tag-sleeve-golden`).
 */

const DIR = join(__dirname, '..', 'golden', 'tag-sleeve');
const DOC = join(__dirname, '..', '..', 'docs', 'pricing-validation-tag-sleeve.md');
const TOLERANCE = 0.005;
const update = process.env['UPDATE_GOLDEN'] === '1';

type Summary = ReturnType<typeof summarise>;

function summarise(result: FoldingResult) {
  return {
    selection: result.selection,
    options: result.options.map((o) => ({
      optionKey: o.optionKey,
      error: o.error ? `${o.error.code}: ${o.error.detail}` : null,
      steps: o.steps.map((s) =>
        s
          ? {
              qty: s.qty,
              productionRun: s.boxAmount,
              buyPrice: s.buyPrice,
              perPcs: s.perPcs,
              sum: s.sum,
              vatPrice: s.vatPrice,
              designFee: s.designFee,
              structureDesignFee: s.structureDesignFee,
              total: s.total,
              leadTimeDays: s.leadTimeDays,
              marginPct: s.marginPct,
              parts: s.parts.map((p) => ({
                partKey: p.partKey,
                sheet: p.layout.layout.sheet.sheetKey,
                layoutStandard: p.layout.layout.layoutStandard,
                layoutAmount: p.layout.layout.layoutAmount,
                pressSheets: p.layout.waste.totalSheets,
                cost: p.layout.totalCost,
                buyPrice: p.buyPrice,
                targetMarginPct: p.forSale.targetMarginPct,
                perPcs: p.forSale.perPcs,
              })),
            }
          : null,
      ),
    })),
  };
}

function compare(actual: unknown, expected: unknown, path: string, errors: string[]): void {
  if (typeof expected === 'number' && typeof actual === 'number') {
    if (Math.abs(actual - expected) > TOLERANCE) errors.push(`${path}: ${actual} ≠ ${expected}`);
    return;
  }
  if (Array.isArray(expected) && Array.isArray(actual)) {
    if (actual.length !== expected.length)
      errors.push(`${path}: length ${actual.length} ≠ ${expected.length}`);
    expected.forEach((e, i) => compare(actual[i], e, `${path}[${i}]`, errors));
    return;
  }
  if (expected && typeof expected === 'object' && actual && typeof actual === 'object') {
    for (const [k, v] of Object.entries(expected))
      compare((actual as Record<string, unknown>)[k], v, `${path}.${k}`, errors);
    return;
  }
  if (actual !== expected) errors.push(`${path}: ${JSON.stringify(actual)} ≠ ${JSON.stringify(expected)}`);
}

const money = (n: number) => n.toFixed(2);
const replacer = (_: string, value: unknown) => (value instanceof Set ? [...value] : value);

function renderDoc(results: { c: GoldenCase; s: Summary }[]): string {
  const lines: string[] = [
    '# Tag & sleeve pricing — validation cases (U-B6)',
    '',
    '> **Status: pending business sign-off.** Generated by `UPDATE_GOLDEN=1` with `--testPathPatterns tag-sleeve-golden`',
    '> from `test/golden/tag-sleeve/cases.ts`; do not edit by hand. Calculator version `' +
      TAG_SLEEVE_CALCULATOR_VERSION +
      '`.',
    '',
    '## How these were derived and how to sign them off',
    '- Legacy prices a tag or sleeve on the **folding** engine: `TagAndSleeveCalculator::fromCS` maps it to a flat folding',
    '  blank (patterns 33–36, `dw = w`, `dl = l`, d = 0) and calls `FoldingCalculator::calculate` (port map',
    '  `docs/legacy/05-tag-sleeve-port-map.md` §0). getpack does the same over the folding port, whose formulas are checked',
    '  piece by piece by hand-derived unit vectors and by `docs/pricing-validation-folding.md`. The expected values below',
    "  are the port's results; the cases exercise what the tag port adds.",
    "- The 20 cases price complete, **made-up** price lists (the folding cases' lists; no real supplier data, D-005). To",
    '  sign off, the business team enters the same rows for a test factory in a Locopack staging copy (folding print types,',
    '  the factory enabled for packaging 5), runs the CS tag calculator (`/cs/tag`) with the same configuration, and',
    '  compares the per-piece price and total. Expect sub-satang differences where Locopack stores prices as `FLOAT`.',
    "- Known, intended differences from Locopack (port map §5): T1 the factory's **tag & sleeve** price list and sell",
    '  tables instead of its folding rows; T3–T5 one option per factory × print type, the lower buy price wins (legacy',
    '  threw or kept the dearer print type); T8 assembly amounts and sizes are forwarded; T18 the tag design fee once per',
    '  quote and no structure fee; T21 a quantity without a price routes to RFQ. Kept from legacy: finish 2 offset only',
    '  (T9), the production minimum raises the run without refusing (T16), die-cut always. Shipping is its own quote line',
    '  (D-013), so no delivery is included here.',
    '',
    '| Business sign-off | Name | Date |',
    '|---|---|---|',
    '| Pricing owner | | |',
    '| Finance | | |',
    '',
  ];
  for (const { c, s } of results) {
    lines.push(`## ${c.id} — ${c.title}`, '', `Legacy: ${c.legacy.map((l) => '`' + l + '`').join(', ')}`, '');
    lines.push(
      '| Option | Qty | Run | Layout | Press sheets | Buy price | Per piece (VAT incl.) | Total (VAT incl.) | Lead time |',
      '|---|---|---|---|---|---|---|---|---|',
    );
    for (const o of s.options) {
      if (o.error) {
        lines.push(`| ${o.optionKey} | — | — | — | — | ${o.error} | — | — | — |`);
        continue;
      }
      o.steps.forEach((st, i) => {
        if (!st) {
          lines.push(`| ${o.optionKey} | ${c.input.quantities[i]} | — | no layout | — | — | — | — | — |`);
          return;
        }
        const p = st.parts
          .map((x) => `${x.sheet} ${x.layoutStandard ? 'std' : 'rot'} ×${x.layoutAmount}`)
          .join('; ');
        const sheets = st.parts.map((x) => x.pressSheets).join('; ');
        lines.push(
          `| ${o.optionKey} | ${st.qty} | ${st.productionRun} | ${p} | ${sheets} | ${money(st.buyPrice)} | ${money(st.perPcs)} | ${money(st.total)} | ${st.leadTimeDays} d |`,
        );
      });
    }
    lines.push('', `Selected per quantity: ${s.selection.map((x) => x ?? 'none').join(', ')}`, '');
    lines.push('<details><summary>Configuration and price rows</summary>', '', '```json');
    lines.push(JSON.stringify({ input: c.input, options: c.options }, replacer, 2));
    lines.push('```', '', '</details>', '');
  }
  return lines.join('\n');
}

describe('tag & sleeve golden cases (U-B6 tag & sleeve)', () => {
  const results = CASES.map((c) => ({
    c,
    s: summarise(tagSleeveCalculator.calculate(c.input, { options: c.options })),
  }));

  if (update) {
    for (const { c, s } of results)
      writeFileSync(join(DIR, `${c.id}.json`), JSON.stringify(s, null, 2) + '\n');
    writeFileSync(DOC, renderDoc(results));
  }

  it('has 20 cases; all but the oversized sheet are priced', () => {
    expect(CASES).toHaveLength(20);
    const unpriced = results.filter(({ s }) => s.selection.some((x) => x === null)).map((r) => r.c.id);
    expect(unpriced).toEqual(['19-too-large']);
  });

  it('refuses finish 2 on digital and engine B, and never charges a structure fee', () => {
    const byId = new Map(results.map((r) => [r.c.id, r.s]));
    expect(byId.get('10-foil-digital-refused')!.options.map((o) => o.error?.split(':')[0] ?? null)).toEqual([
      null,
      'process_not_possible',
    ]);
    expect(byId.get('20-engine-b-refused')!.options[1]!.error).toMatch(/^process_not_possible/);
    const design = byId.get('16-design-fee')!.options[0]!.steps;
    expect(design.map((s) => [s?.designFee, s?.structureDesignFee])).toEqual([
      [1200, 0],
      [1200, 0],
    ]);
  });

  it.each(results.map((r) => [r.c.id, r] as const))(
    '%s matches its golden file within 0.005',
    (_id, { c, s }) => {
      const expected = JSON.parse(readFileSync(join(DIR, `${c.id}.json`), 'utf8')) as Summary;
      const errors: string[] = [];
      compare(s, expected, c.id, errors);
      expect(errors).toEqual([]);
    },
  );
});
