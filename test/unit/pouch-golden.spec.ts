import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  POUCH_CALCULATOR_VERSION,
  pouchCalculator,
  type PouchInput,
  type PouchOption,
  type PouchOptionResult,
} from '@modules/pricing/calculators/pouch/pouch-calculator';

/**
 * Golden pouch cases (U-B6 pouch). The inputs and the expected values are in `test/golden/pouch/golden.json`,
 * written by `test/golden/pouch/cases.py`: the expected values come from the independent Python transcription of the
 * PHP (`reference/pouch_reference.py`), not from this port. Every number must agree within 1e-6. `UPDATE_GOLDEN=1`
 * (with `--testPathPatterns pouch-golden`) rewrites `docs/pricing-validation-pouch.md` from the port's results; the
 * expected values change only by rerunning the Python.
 */

const DIR = join(__dirname, '..', 'golden', 'pouch');
const DOC = join(__dirname, '..', '..', 'docs', 'pricing-validation-pouch.md');
const TOLERANCE = 1e-6;
const update = process.env['UPDATE_GOLDEN'] === '1';

/** The business sign-off (`test/golden/pouch/sign-off.json`), tied to the calculator version and the cases. */
interface SignOff {
  calculatorVersion: string;
  goldenSha256: string;
  evidence: string;
  signatures: { role: string; name: string; date: string }[];
}
const SIGN_OFF = join(DIR, 'sign-off.json');
const signOff: SignOff | null = existsSync(SIGN_OFF)
  ? (JSON.parse(readFileSync(SIGN_OFF, 'utf8')) as SignOff)
  : null;
const goldenSha256 = createHash('sha256')
  .update(readFileSync(join(DIR, 'golden.json')))
  .digest('hex');
const signedOff =
  signOff !== null &&
  signOff.calculatorVersion === POUCH_CALCULATOR_VERSION &&
  signOff.goldenSha256 === goldenSha256 &&
  ['Pricing owner', 'Finance'].every((role) => signOff.signatures.some((s) => s.role === role));

interface GoldenCase {
  key: string;
  title: string;
  input: PouchInput;
  options: PouchOption[];
  expected: unknown;
}

type Summary = ReturnType<typeof summarise>;

function summarise(options: PouchOptionResult[]) {
  const text = (e: { code: string; detail: string } | null) => (e ? `${e.code}: ${e.detail}` : null);
  return options.map((o) => ({
    optionKey: o.optionKey,
    error: text(o.error),
    errors: o.stepErrors.map(text),
    steps: o.steps.map((s) =>
      s
        ? {
            qty: s.qty,
            dl: s.dimension.dl,
            dw: s.dimension.dw,
            calDl: s.dimension.calDl,
            calSqcm: s.dimension.calSqcm,
            pow: s.pow,
            pol: s.pol,
            materialPerPcs: s.materialPerPcs,
            printPerPcs: s.printPerPcs,
            processTotal: s.processes.reduce((a, p) => a + p.pricePerPcs, 0),
            costPerPcs: s.costPerPcs,
            factoryMarginPct: s.factoryMarginPct,
            factoryPricePerPcs: s.factoryPricePerPcs,
            buyPrice: s.buyPrice,
            targetMarginPct: s.targetMarginPct,
            perPcs: s.perPcs,
            sum: s.sum,
            designFee: s.designFee,
            total: s.total,
            leadTimeDays: s.leadTimeDays,
          }
        : null,
    ),
  }));
}

function compare(actual: unknown, expected: unknown, path: string, errors: string[]): void {
  if (typeof expected === 'number' && typeof actual === 'number') {
    if (Math.abs(actual - expected) > TOLERANCE) errors.push(`${path}: ${actual} ≠ ${expected}`);
    return;
  }
  if (Array.isArray(expected) && Array.isArray(actual)) {
    if (actual.length !== expected.length)
      errors.push(`${path}: length ${actual.length} ≠ ${expected.length}`);
    expected.forEach((e, i) => compare(actual[i], e, `${path}[${i}]`, errors));
    return;
  }
  if (expected && typeof expected === 'object' && actual && typeof actual === 'object') {
    for (const [k, v] of Object.entries(expected))
      compare((actual as Record<string, unknown>)[k], v, `${path}.${k}`, errors);
    return;
  }
  if (actual !== expected) errors.push(`${path}: ${JSON.stringify(actual)} ≠ ${JSON.stringify(expected)}`);
}

const money = (n: number) => n.toFixed(2);

function renderDoc(results: { c: GoldenCase; s: Summary }[]): string {
  const lines: string[] = [
    '# Pouch pricing — validation cases (U-B6)',
    '',
    (signedOff
      ? `> **Status: signed off** (${signOff.signatures.map((x) => `${x.role} ${x.date}`).join(', ')}).`
      : '> **Status: pending business sign-off.**') +
      ' Generated by `UPDATE_GOLDEN=1` with `--testPathPatterns pouch-golden` from',
    '> `test/golden/pouch/golden.json`; do not edit by hand. Calculator version `' +
      POUCH_CALCULATOR_VERSION +
      '`.',
    '',
    '## How these were derived and how to sign them off',
    '- No Locopack dump with pouch calculations exists (legacy pouch writes no `calculate_logs`). The expected values were',
    '  derived twice, independently, from the PHP: once by the TypeScript port and once by a Python transcription that keeps',
    '  the PHP statement order (`test/golden/pouch/reference/pouch_reference.py`: `calculateDimension`, the film per pouch,',
    '  `calculatePaperPrice`, `calculatePrinting`, `calculateAssembly`, `calculateCost`, `calculateMargin`). The two agree on',
    '  every number below within 1e-6 (`test/unit/pouch-golden.spec.ts`).',
    '- The 20 cases price complete, **made-up** price lists (no real supplier data, D-005). To sign off, the business team',
    '  enters the same rows for a test factory in a Locopack staging copy (`factory_match_print_type` pouch columns, `paper`,',
    '  `color`, `assembly_prices` with groups 36 / 37, `production_conditions`, `factory_margins`, `locopack_margins`), runs',
    '  the CS pouch calculator (`/cs/pouch`) with a fixed delivery, and compares the cost per piece, the factory price per',
    '  piece and the price per piece before delivery (`margin.sale_price_per_pcs`).',
    '- Known, intended differences from Locopack (port map `docs/legacy/05-pouch-port-map.md` §9): a quantity below the',
    "  factory's minimum is refused (legacy raised it and charged the raised run); a missing price row (option, zipper,",
    '  lamination / making band, minimum band) refuses that factory instead of failing the whole request; one option per',
    "  factory × print type; Packio's sell table (quantity tiers, fix cost, design fee) and the dated VAT rate instead of",
    '  `locopack_margins` and the 1.07 literal; an unprinted pouch has no print line; delivery is its own quote line (D-013).',
    '  The lamination (4 THB/m² × 0.8 m) and pouch-making (more than 10 000 → 0.2 THB) constants legacy hard-coded are',
    '  print-type terms with those values.',
    '',
    '| Business sign-off | Name | Date |',
    '|---|---|---|',
    ...['Pricing owner', 'Finance'].map((role) => {
      const x = signedOff ? signOff.signatures.find((y) => y.role === role) : undefined;
      return `| ${role} | ${x?.name ?? ''} | ${x?.date ?? ''} |`;
    }),
    ...(signedOff ? ['', `Evidence: ${signOff.evidence}`] : []),
    '',
  ];
  for (const { c, s } of results) {
    lines.push(`## ${c.key} — ${c.title}`, '');
    lines.push(
      '| Option | Qty | Film across × per pouch (mm) | Cost / pc | Factory price / pc | Buy price | Per piece (VAT incl.) | Total (VAT incl.) | Lead time |',
      '|---|---|---|---|---|---|---|---|---|',
    );
    for (const o of s) {
      if (o.error) {
        lines.push(`| ${o.optionKey} | — | — | ${o.error} | — | — | — | — | — |`);
        continue;
      }
      o.steps.forEach((st, i) => {
        if (!st) {
          lines.push(
            `| ${o.optionKey} | ${c.input.quantities[i]} | ${o.errors[i]} | — | — | — | — | — | — |`,
          );
          return;
        }
        lines.push(
          `| ${o.optionKey} | ${st.qty} | ${st.calDl} × ${money(st.pow)} (web ${st.pol}) | ${money(st.costPerPcs)} | ${money(st.factoryPricePerPcs)} | ${money(st.buyPrice)} | ${money(st.perPcs)} | ${money(st.total)} | ${st.leadTimeDays} d |`,
        );
      });
    }
    lines.push('', '<details><summary>Configuration and price rows</summary>', '', '```json');
    lines.push(JSON.stringify({ input: c.input, options: c.options }, null, 2));
    lines.push('```', '', '</details>', '');
  }
  return lines.join('\n');
}

describe('pouch golden cases (U-B6 pouch)', () => {
  const cases = JSON.parse(readFileSync(join(DIR, 'golden.json'), 'utf8')) as GoldenCase[];
  const results = cases.map((c) => ({
    c,
    s: summarise(pouchCalculator.calculate(c.input, { options: c.options }).options),
  }));

  if (update) writeFileSync(DOC, renderDoc(results));

  it('keeps its sign-off current: re-sign after any change to the calculator version or the cases', () => {
    if (signOff === null) return; // not signed yet: the doc says pending
    expect({ calculatorVersion: signOff.calculatorVersion, goldenSha256: signOff.goldenSha256 }).toEqual({
      calculatorVersion: POUCH_CALCULATOR_VERSION,
      goldenSha256,
    });
    expect(signedOff).toBe(true);
  });

  it('has 20 cases; all but the three refusal cases price a quantity', () => {
    expect(cases).toHaveLength(20);
    const unpriced = results
      .filter(({ s }) => !s.some((o) => o.steps.some((st) => st !== null)))
      .map((r) => r.c.key);
    expect(unpriced).toEqual(['07-too-wide', '15-zipper-no-price', '16-option-not-offered']);
  });

  it.each(results.map((r) => [r.c.key, r] as const))(
    '%s agrees with the Python transcription of the PHP within 1e-6',
    (_key, { c, s }) => {
      const errors: string[] = [];
      compare(s, c.expected, c.key, errors);
      expect(errors).toEqual([]);
    },
  );
});
