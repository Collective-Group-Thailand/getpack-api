import { randomUUID } from 'node:crypto';

import { MoneyDecimal } from '@common/money/money';
import { bangkokDate } from '@common/time/bangkok';
import { OBJECT_STORAGE, type ObjectStorage } from '@integrations/s3/object-storage.port';
import { readObject } from '@modules/payouts/read-object';
import { ReportsService } from '@modules/reports/reports.service';
import ExcelJS from 'exceljs';

import { type DevFolding } from '../../prisma/seed/dev-folding';
import {
  addAddress,
  as,
  customerToken,
  foldingBackToRfq,
  foldingReady,
  postcodes,
  saveQuote,
  seedShipping,
  setFlag,
  staffToken,
} from '../support/commerce-e2e';
import { bootFulfilmentApp, type FulfilmentApp, payDue } from '../support/fulfilment-e2e';

interface Definition {
  key: string;
  filters: { key: string; kind: string }[];
  columns: { key: string; type: string }[];
}
interface Run {
  id: string;
  status: string;
  rowCount: number | null;
  scheduleId: string | null;
}

/**
 * B6.2 operational reports: the catalogue follows the caller's permissions, every report previews against real
 * data, exports are generated by the worker and downloaded through an audited signed URL, and schedules resolve
 * their relative period at run time and notify only recipients who may read the report.
 */
describe('operational reports (e2e, B6.2)', () => {
  let ctx: FulfilmentApp;
  let fixture: DevFolding;
  let admin: string;
  let finance: string;
  let manager: string;
  let groupCode: string;
  const today = bangkokDate(new Date());
  const month = today.slice(0, 7);

  beforeAll(async () => {
    ctx = await bootFulfilmentApp();
    fixture = await foldingReady(ctx);
    await seedShipping(ctx, fixture.factoryPublicId, postcodes(ctx, 1));
    await setFlag(ctx, 'payments.scb', true);
    [admin, finance, manager] = await Promise.all([
      staffToken(ctx, 'superadmin'),
      staffToken(ctx, 'finance'),
      staffToken(ctx, 'finance_manager'),
    ]);
    const { token } = await customerToken(ctx, 1);
    const address = await addAddress(ctx, token, postcodes(ctx, 1)[0]!);
    const quote = await saveQuote(ctx, token, fixture, [1000]);
    await as(ctx, token)
      .post('/v1/store/cart/items', {
        quoteId: quote.id,
        quoteOptionId: quote.options[0]!.id,
        designOption: 'own_file',
        destinations: [{ addressId: address.id, quantity: 1000 }],
      })
      .expect(201);
    const group = (
      await as(ctx, token).post('/v1/store/checkout', {}).set('Idempotency-Key', randomUUID()).expect(201)
    ).body as { id: string; groupCode: string };
    groupCode = group.groupCode;
    await payDue(ctx, token, group.id);
    await ctx.pump();
  });

  afterAll(async () => {
    await setFlag(ctx, 'payments.scb', false);
    await foldingBackToRfq(ctx);
    await ctx?.app.close();
  });

  const filtersFor = (d: Definition) =>
    d.filters.find((f) => f.key === 'period')?.kind === 'as_of'
      ? `asOf=${today}`
      : d.filters.find((f) => f.key === 'period')?.kind === 'month'
        ? `month=${month}`
        : `from=${today}&to=${today}`;

  it('lists the reports a role may read and previews every one of them', async () => {
    const all = (await as(ctx, admin).get('/v1/admin/reports').expect(200)).body as Definition[];
    expect(all.map((d) => d.key).sort()).toEqual(
      [
        'ap_aging',
        'ar_aging',
        'campaign_usage',
        'claims',
        'factory_scorecards',
        'orders',
        'payments_by_channel',
        'payout_history',
        'points_liability',
        'quotations',
        'sales',
        'sales_tax',
      ].sort(),
    );
    const marketing = (
      await as(ctx, await staffToken(ctx, 'marketing'))
        .get('/v1/admin/reports')
        .expect(200)
    ).body as Definition[];
    expect(marketing.map((d) => d.key).sort()).toEqual(['campaign_usage', 'points_liability']);

    for (const d of all) {
      const res = await as(ctx, admin).get(`/v1/admin/reports/${d.key}/preview?${filtersFor(d)}`);
      expect({ key: d.key, status: res.status }).toEqual({ key: d.key, status: 200 });
      const body = res.body as { columns: { key: string }[]; rows: Record<string, unknown>[] };
      expect(body.columns.map((c) => c.key)).toEqual(d.columns.map((c) => c.key));
      for (const row of body.rows)
        expect(Object.keys(row).sort()).toEqual(d.columns.map((c) => c.key).sort());
    }

    // The sales register carries today's paid group with its amounts.
    const sales = (
      await as(ctx, await staffToken(ctx, 'marketing'))
        .get(`/v1/admin/reports/sales/preview?from=${today}&to=${today}`)
        .expect(403)
    ).body;
    expect(sales.code).toBe('auth.forbidden');
    const preview = (
      await as(ctx, admin).get(`/v1/admin/reports/sales/preview?period=month_to_date`).expect(200)
    ).body as {
      filters: { from: string };
      rows: { groupCode: string; gross: string; groupStatus: string }[];
    };
    expect(preview.filters.from).toBe(`${month}-01`);
    // U-B0.3: the totals row is computed over every row; the catalogue carries the menu group.
    const totalled = (
      await as(ctx, admin).get(`/v1/admin/reports/sales/preview?period=month_to_date`).expect(200)
    ).body as {
      columns: { key: string; type: string; total: boolean }[];
      rows: Record<string, string | number | null>[];
      totals: Record<string, string | number>;
      truncated: boolean;
      generatedAt: string;
    };
    expect(totalled.generatedAt).toMatch(/\+07:00$/);
    const gross = totalled.columns.find((c) => c.key === 'gross')!;
    expect(gross.total).toBe(true);
    if (!totalled.truncated)
      expect(totalled.totals['gross']).toBe(
        totalled.rows.reduce((a, r) => a.add(String(r['gross'] ?? '0')), new MoneyDecimal(0)).toFixed(2),
      );
    expect(totalled.columns.filter((c) => c.type === 'text').every((c) => !c.total)).toBe(true);
    expect(all.every((d) => typeof (d as unknown as { group: string }).group === 'string')).toBe(true);

    // U-B0.3: a staff list exported as a file, behind the list's permission and reports.export.
    const file = (
      await as(ctx, admin)
        .post('/v1/admin/exports', {
          resource: 'orders',
          format: 'csv',
          query: { status: 'paid_for_production' },
        })
        .expect(200)
    ).body as { fileId: string; url: string; rows: number; truncated: boolean };
    expect(file).toMatchObject({ url: expect.any(String), truncated: false });
    await as(ctx, admin)
      .post('/v1/admin/exports', { resource: 'orders', format: 'csv', query: { status: 'nope' } })
      .expect(422);
    await as(ctx, await staffToken(ctx, 'cs'))
      .post('/v1/admin/exports', { resource: 'orders', format: 'xlsx' })
      .expect(403);
    expect(
      await ctx.prisma.auditLog.count({ where: { action: 'export.generated', resourceType: 'orders' } }),
    ).toBeGreaterThan(0);
    const mine = preview.rows.find((r) => r.groupCode === groupCode)!;
    const order = await ctx.prisma.order.findFirstOrThrow({ where: { orderGroup: { groupCode } } });
    expect(mine).toMatchObject({ gross: order.grossAmount.toFixed(2), groupStatus: 'in_progress' });

    // Payments carry the SCB payment of the group.
    const payments = (
      await as(ctx, admin)
        .get(`/v1/admin/reports/payments_by_channel/preview?from=${today}&to=${today}&provider=scb`)
        .expect(200)
    ).body as { rows: { groupCode: string; provider: string }[] };
    expect(payments.rows.some((r) => r.groupCode === groupCode && r.provider === 'scb')).toBe(true);

    // Validation: required, unknown, impossible, and an unknown report.
    expect(
      (await as(ctx, admin).get('/v1/admin/reports/sales/preview').expect(422)).body.errors[0].path,
    ).toBe('from');
    expect(
      (
        await as(ctx, admin)
          .get(`/v1/admin/reports/sales/preview?asOf=${today}&from=${today}&to=${today}`)
          .expect(422)
      ).body.errors[0],
    ).toMatchObject({ path: 'asOf', code: 'unknown' });
    await as(ctx, admin).get('/v1/admin/reports/nope/preview').expect(404);
  });

  it('exports through the worker, downloads by an audited signed URL, and reads back the workbook', async () => {
    await as(ctx, await staffToken(ctx, 'cs'))
      .post('/v1/admin/reports/sales/exports', { format: 'xlsx', filters: { from: today, to: today } })
      .expect(403);
    const queued = (
      await as(ctx, admin)
        .post('/v1/admin/reports/sales/exports', { format: 'xlsx', filters: { from: today, to: today } })
        .expect(202)
    ).body as Run;
    expect(queued.status).toBe('queued');
    await as(ctx, admin).get(`/v1/admin/report-runs/${queued.id}/file`).expect(409);
    expect(await ctx.app.get(ReportsService).processRuns()).toBeGreaterThanOrEqual(1);
    const done = (await as(ctx, admin).get(`/v1/admin/report-runs/${queued.id}`).expect(200)).body as Run;
    expect(done.status).toBe('succeeded');
    const preview = (
      await as(ctx, admin).get(`/v1/admin/reports/sales/preview?from=${today}&to=${today}`).expect(200)
    ).body as { rows: unknown[]; truncated: boolean };
    if (!preview.truncated) expect(done.rowCount).toBe(preview.rows.length);
    await as(ctx, admin).get(`/v1/admin/report-runs/${queued.id}/file`).expect(200);
    expect(
      await ctx.prisma.auditLog.count({
        where: { action: 'report.downloaded', resourcePublicId: queued.id },
      }),
    ).toBe(1);

    const run = await ctx.prisma.reportRun.findUniqueOrThrow({
      where: { publicId: queued.id },
      include: { file: true },
    });
    const wb = new ExcelJS.Workbook();
    await wb.xlsx.load(
      (await readObject(
        ctx.app.get<ObjectStorage>(OBJECT_STORAGE),
        run.file!.storageKey,
      )) as unknown as ArrayBuffer,
    );
    const sheet = wb.getWorksheet('Report')!;
    expect(sheet.getRow(1).getCell(1).value).toBe('Placed at / วันที่สั่งซื้อ');
    expect(sheet.rowCount).toBe(done.rowCount! + 1);

    // CSV of the AR aging (as of today), by an auditor (read-only role with export).
    const auditor = await staffToken(ctx, 'auditor');
    const csv = (
      await as(ctx, auditor)
        .post('/v1/admin/reports/ar_aging/exports', { format: 'csv', filters: { asOf: today } })
        .expect(202)
    ).body as Run;
    await ctx.app.get(ReportsService).processRuns();
    const csvRun = await ctx.prisma.reportRun.findUniqueOrThrow({
      where: { publicId: csv.id },
      include: { file: true },
    });
    expect(csvRun.status).toBe('succeeded');
    const text = (
      await readObject(ctx.app.get<ObjectStorage>(OBJECT_STORAGE), csvRun.file!.storageKey)
    ).toString('utf8');
    expect(text.startsWith('﻿"Party / ประเภท"')).toBe(true);
    // Another user's run is not visible without reports.schedule.
    await as(ctx, finance).get(`/v1/admin/report-runs/${csv.id}`).expect(200); // finance holds reports.schedule
    await as(ctx, await staffToken(ctx, 'logistics'))
      .get(`/v1/admin/report-runs/${csv.id}`)
      .expect(404);
  });

  it('schedules with a relative period for permitted recipients and notifies them', async () => {
    const financeUser = await ctx.prisma.user.findFirstOrThrow({
      where: { email: 'finance@example.invalid' },
    });
    const csUser = await ctx.prisma.user.findFirstOrThrow({ where: { email: 'cs@example.invalid' } });
    const body = {
      reportKey: 'ar_aging',
      name: 'AR aging weekly (e2e)',
      format: 'xlsx',
      frequency: 'weekly',
      runAt: '07:00',
      dayOfWeek: 1,
      filters: { period: 'previous_day' },
      recipientIds: [financeUser.publicId],
    };
    expect(
      (
        await as(ctx, manager)
          .post('/v1/admin/report-schedules', { ...body, recipientIds: [csUser.publicId] })
          .expect(422)
      ).body.code,
    ).toBe('reports.recipient_not_allowed');
    expect(
      (
        await as(ctx, manager)
          .post('/v1/admin/report-schedules', { ...body, filters: { asOf: today } })
          .expect(422)
      ).body.errors[0].path,
    ).toBe('filters.period');
    expect(
      (
        await as(ctx, manager)
          .post('/v1/admin/report-schedules', { ...body, dayOfWeek: undefined })
          .expect(422)
      ).body.errors[0].path,
    ).toBe('frequency');
    const schedule = (await as(ctx, manager).post('/v1/admin/report-schedules', body).expect(201)).body as {
      id: string;
      nextRunAt: string;
      recipients: { id: string }[];
    };
    expect(schedule.recipients).toEqual([{ id: financeUser.publicId, displayName: financeUser.displayName }]);
    expect(new Date(schedule.nextRunAt).getTime()).toBeGreaterThan(Date.now());

    // Due: the worker queues the run with the period resolved at run time, and moves the schedule on.
    const service = ctx.app.get(ReportsService);
    const at = new Date(new Date(schedule.nextRunAt).getTime() + 1000);
    await service.queueDue(at);
    const row = await ctx.prisma.reportSchedule.findUniqueOrThrow({ where: { publicId: schedule.id } });
    expect(row.nextRunAt!.getTime() - new Date(schedule.nextRunAt).getTime()).toBe(7 * 86_400_000);
    const scheduled = await ctx.prisma.reportRun.findFirstOrThrow({
      where: { schedule: { publicId: schedule.id } },
    });
    expect(scheduled.filters).toEqual({ asOf: bangkokDate(new Date(at.getTime() - 86_400_000)) });
    await service.queueDue(at); // the same due time is claimed once
    expect(await ctx.prisma.reportRun.count({ where: { schedule: { publicId: schedule.id } } })).toBe(1);

    const now = (
      await as(ctx, manager).post(`/v1/admin/report-schedules/${schedule.id}/actions/run`).expect(202)
    ).body as Run;
    expect(now.scheduleId).toBe(schedule.id);
    await service.processRuns();
    await ctx.pump({ notifications: true });
    const events = await ctx.prisma.domainEvent.findMany({
      where: { type: 'report_run.completed', aggregateId: now.id },
    });
    expect(events).toHaveLength(1);
    const notifications = await ctx.prisma.notification.findMany({ where: { eventId: events[0]!.id } });
    expect(notifications.map((n) => `${n.recipientUserId}:${n.channel}`).sort()).toEqual([
      `${financeUser.id}:email`,
      `${financeUser.id}:in_app`,
    ]);

    // Recipient sees the run; schedules are deactivated, not edited.
    expect(
      (
        (await as(ctx, finance).get(`/v1/admin/report-runs?scheduleId=${schedule.id}`).expect(200))
          .body as Run[]
      ).length,
    ).toBe(2);
    await as(ctx, manager).post(`/v1/admin/report-schedules/${schedule.id}/actions/deactivate`).expect(200);
    expect(
      (
        await as(ctx, manager)
          .post(`/v1/admin/report-schedules/${schedule.id}/actions/deactivate`)
          .expect(409)
      ).body.code,
    ).toBe('reports.schedule_state');
    await as(ctx, manager).post(`/v1/admin/report-schedules/${schedule.id}/actions/activate`).expect(200);
  });
});
